-- 1. TABELA DE VAGAS (Caso não exista)
create table if not exists vagas (
  id text primary key,
  empresa text,
  cargo text,
  modalidade text,
  localizacao text,
  turno text,
  prazo text,
  requisitos text,
  link text unique,
  data_coleta text,
  notificada boolean default false,
  status text default 'para_aplicar',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table vagas enable row level security;

create policy "Permitir leitura publica de vagas" 
  on vagas for select 
  using (true);

create policy "Permitir gerenciamento de vagas pelo backend" 
  on vagas for all 
  using (true) 
  with check (true);

-- 2. TABELA DE TELEMETRIA E HISTÓRICO DE VARREDURAS
create table if not exists historico_execucoes (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  timestamp text not null,
  status text not null,
  is_erro boolean default false,
  duracao_segundos integer default 0,
  mensagem text,
  total_vagas integer default 0
);

alter table historico_execucoes enable row level security;

create policy "Permitir leitura publica do historico" 
  on historico_execucoes for select 
  using (true);

create policy "Permitir insercao pelo backend" 
  on historico_execucoes for insert 
  with check (true);
